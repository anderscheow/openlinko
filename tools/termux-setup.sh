#!/data/data/com.termux/files/usr/bin/bash
# OpenLinko on an old Android phone (Termux). The phone becomes the always-on box:
# leave it on the charger and on Wi-Fi, and it logs your car 24/7.
#
# One-time, inside Termux (install Termux from F-Droid, NOT the Play Store build):
#   pkg install -y git && git clone https://github.com/GodrezJr2/openlinko ~/openlinko
#   bash ~/openlinko/tools/termux-setup.sh
#
# Then:  openlinko start | stop | restart | status | log | update
#
# Flags:  --port N (default 8088)   --no-start (set up only)
set -euo pipefail

PORT=8088
START=1
while [ $# -gt 0 ]; do
  case "$1" in
    --port)     PORT="$2"; shift ;;
    --port=*)   PORT="${1#*=}" ;;
    --no-start) START=0 ;;
    -h|--help)  sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown flag: $1 (try --help)" >&2; exit 2 ;;
  esac
  shift
done

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf '\033[31m!! %s\033[0m\n' "$*" >&2; exit 1; }

[ -n "${PREFIX:-}" ] && [ -d "$PREFIX" ] && case "$PREFIX" in *com.termux*) true ;; *) false ;; esac \
  || die "This script is for Termux on Android. On a PC/server use tools/install.sh or start.bat."

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$PREFIX/bin/openlinko"

# ------------------------------------------------------------------ packages
say "Installing Python (Termux packages)"
pkg update -y >/dev/null 2>&1 || true
pkg install -y python git >/dev/null
python - <<'PY' || die "Python 3.10+ is needed; run 'pkg upgrade' and try again."
import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)
PY
say "Installing the two Python libraries it needs"
pip install --quiet --disable-pip-version-check requests websocket-client

# ------------------------------------------------------------------ control command
say "Installing the 'openlinko' command"
cat > "$BIN" <<EOF
#!/data/data/com.termux/files/usr/bin/bash
# OpenLinko control (generated by tools/termux-setup.sh)
REPO="$REPO"
PORT="\${OPENLINKO_PORT:-$PORT}"
EOF
cat >> "$BIN" <<'EOF'
STATE="$HOME/.openlinko"; mkdir -p "$STATE"
PIDF="$STATE/loop.pid"; LOG="$STATE/openlinko.log"

running() { [ -f "$PIDF" ] && kill -0 "$(cat "$PIDF")" 2>/dev/null; }

lan_ip() {
  python - <<'PY' 2>/dev/null
import socket
s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
try:
    s.connect(("192.0.2.1", 9)); print(s.getsockname()[0])
except Exception:
    pass
PY
}

start() {
  if running; then echo "already running (pid $(cat "$PIDF"))"; return 0; fi
  command -v termux-wake-lock >/dev/null && termux-wake-lock   # keep Android from sleeping it
  # supervisor loop: if the dashboard ever exits, start it again after 10 s
  nohup bash -c '
    trap "kill -TERM \$child 2>/dev/null; wait \$child; exit 0" TERM INT
    while true; do
      echo "[$(date "+%F %T")] starting OpenLinko on :'"$PORT"'"
      python -u "'"$REPO"'/tools/run.py" '"$PORT"' --no-browser & child=$!
      wait $child
      echo "[$(date "+%F %T")] exited ($?), restarting in 10 s"; sleep 10
    done' >>"$LOG" 2>&1 &
  echo $! >"$PIDF"
  sleep 4
  status
}

stop() {
  if running; then kill -TERM "$(cat "$PIDF")" 2>/dev/null; sleep 3; fi
  pkill -f "python[0-9.]* -u $REPO/tools/(run|server|logger).py" 2>/dev/null || true
  rm -f "$PIDF"
  command -v termux-wake-unlock >/dev/null && termux-wake-unlock
  echo "stopped"
}

status() {
  if running; then
    ip="$(lan_ip)"
    echo "OpenLinko is running (pid $(cat "$PIDF"))"
    echo "  on this phone:   http://localhost:$PORT"
    [ -n "$ip" ] && echo "  on your Wi-Fi:   http://$ip:$PORT"
    if command -v curl >/dev/null; then
      curl -fsS -m 3 "http://127.0.0.1:$PORT/api/status" >/dev/null 2>&1 \
        && echo "  dashboard answers: OK" || echo "  dashboard not answering yet (see: openlinko log)"
    fi
  else
    echo "OpenLinko is not running. Start it with: openlinko start"
  fi
}

case "${1:-status}" in
  start)   start ;;
  stop)    stop ;;
  restart) stop; start ;;
  status)  status ;;
  log)     tail -n "${2:-60}" -f "$LOG" ;;
  update)  git -C "$REPO" pull --ff-only && { stop; start; } ;;
  *) echo "usage: openlinko start|stop|restart|status|log|update"; exit 2 ;;
esac
EOF
chmod +x "$BIN"
pkg install -y curl >/dev/null 2>&1 || true

# ------------------------------------------------------------------ auto-start at boot
say "Auto-start when the phone boots"
mkdir -p "$HOME/.termux/boot"
cat > "$HOME/.termux/boot/openlinko" <<EOF
#!/data/data/com.termux/files/usr/bin/sh
termux-wake-lock
bash $BIN start
EOF
chmod +x "$HOME/.termux/boot/openlinko"
echo "    needs the Termux:Boot app (F-Droid), opened once after installing."

# ------------------------------------------------------------------ start
if [ "$START" = 1 ]; then
  say "Starting OpenLinko"
  bash "$BIN" start
fi

cat <<EOF

Done. Open the address above in your browser and sign in with your CarLinko account
(a SECOND account linked to your car is safest, see the README).

Keep it alive on Android:
  1. Settings > Apps > Termux > Battery > "Unrestricted" (no battery optimisation).
  2. Keep the phone on the charger and on Wi-Fi.
  3. Install Termux:Boot (F-Droid) and open it once, so OpenLinko starts after a reboot.
  4. To reach it from outside your home: install the Tailscale app on this phone and yours.

Commands: openlinko start | stop | restart | status | log | update
EOF
